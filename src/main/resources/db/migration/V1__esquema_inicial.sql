-- Tablas del ejemplo (DAS v1.3, Figura 5). Existencias y umbral como NUMERIC(14,2).

CREATE TABLE articulo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(8)     NOT NULL UNIQUE,
    nombre         VARCHAR(100)   NOT NULL,
    tipo           VARCHAR(20)    NOT NULL,
    existencias    NUMERIC(14, 2) NOT NULL DEFAULT 0,
    umbral_minimo  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    -- Última barrera de la integridad: ninguna salida puede dejar existencias negativas.
    CONSTRAINT ck_articulo_existencias CHECK (existencias >= 0)
);

CREATE TABLE movimiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    articulo_id     BIGINT         NOT NULL REFERENCES articulo (id),
    tipo            VARCHAR(10)    NOT NULL,
    origen          VARCHAR(12)    NOT NULL,
    cantidad        NUMERIC(14, 2) NOT NULL CHECK (cantidad > 0),
    fecha           DATE           NOT NULL,
    referencia      VARCHAR(30)    NOT NULL,
    solicitud_id    UUID           NOT NULL,
    fecha_registro  TIMESTAMPTZ    NOT NULL
);

CREATE TABLE notificacion (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    articulo_id           BIGINT      NOT NULL REFERENCES articulo (id),
    estado                VARCHAR(12) NOT NULL,
    contenido             TEXT        NOT NULL,
    fecha_creacion        TIMESTAMPTZ NOT NULL,
    fecha_ultimo_intento  TIMESTAMPTZ,
    fecha_envio           TIMESTAMPTZ
);
